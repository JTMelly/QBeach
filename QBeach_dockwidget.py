    def resetGrid(self):
        canvas = self.iface.mapCanvas()
        extentCenter = canvas.extent().center()
        self.dsbEasting.setValue(extentCenter.x())
        self.dsbNorthing.setValue(extentCenter.y())
        self.dsbXdist.setValue(DEFAULT_SETTINGS['distx'])
        self.dsbYdist.setValue(DEFAULT_SETTINGS['disty'])
        self.dsbXresolution.setValue(DEFAULT_SETTINGS['resx'])
        self.dsbYresolution.setValue(DEFAULT_SETTINGS['resy'])
        self.dsbRotation.setValue(DEFAULT_SETTINGS['rotation'])
        self.visualizer.clear()

    def getGridParams(self):
        return {
            'originEasting': self.dsbEasting.value(),
            'originNorthing': self.dsbNorthing.value(),
            'distx': self.dsbXdist.value(),
            'disty': self.dsbYdist.value(),
            'dx': self.dsbXresolution.value(),
            'dy': self.dsbYresolution.value(),
            'angle': self.dsbRotation.value()
        }

    def drawGrid(self):
        p = self.getGridParams()
        worldROI, E_world, N_world = calculate_grid(p)
        self.visualizer.draw(worldROI, E_world, N_world,
                             DEFAULT_SETTINGS['skip_x'],
                             DEFAULT_SETTINGS['skip_y'])

    def exportBathy(self):

        bathy_layer = self.mlcbBathySource.currentLayer()
        output_dir = self.fwSetwd.filePath()

        if not bathy_layer or not isinstance(bathy_layer, QgsRasterLayer):
            QtWidgets.QMessageBox.warning(
                self,
                "Invalid Source",
                "Please select a valid elevation (depth) raster layer."
            )
            return
        if not self.visualizer.roi_rubberband:
            QtWidgets.QMessageBox.warning(
                self,
                "No Grid",
                "Please draw a grid before interpolating/exporting."
            )
            return
        if not output_dir or not os.path.isdir(output_dir):
            QtWidgets.QMessageBox.warning(
                self,
                "Invalid Path",
                "Please select a valid output directory."
            )
            return

        self.iface.messageBar().pushMessage(
            "QBeach",
            "Extracting bathymetry...",
            level=QGIS_INFO,
            duration=2
        )

        # get XB grid
        p = self.getGridParams()
        _worldROI, E_world, N_world = calculate_grid(p)

        # Sample raster at grid nodes
        Z_world = sample_raster_at_grid(bathy_layer, E_world, N_world)

        try:
            np.savetxt(os.path.join(output_dir, "x.grd"), E_world, fmt="%.4f")
            np.savetxt(os.path.join(output_dir, "y.grd"), N_world, fmt="%.4f")
            np.savetxt(
                os.path.join(output_dir, "bed.dep"),
                Z_world,
                fmt="%.4f"
            )

            QTimer.singleShot(2500, lambda: QtWidgets.QMessageBox.information(
                self, "Success", f".grd and .dep files saved to {output_dir}"))
        except FILE_IO_ERRORS as exc:
            QtWidgets.QMessageBox.critical(
                self,
                "Error",
                f"Failed to save files: {exc}"
            )

    def exportOptionalFiles(self):
        output_dir = self.fwSetwdBB2.filePath()
        path_x = self.qgsfwXgridBB.filePath()
        path_y = self.qgsfwYgridBB.filePath()
        path_z = self.qgsfwBedDepBB.filePath()

        paths = [path_x, path_y, path_z]

        if not all(paths) or not all(os.path.isfile(p) for p in paths):
            QtWidgets.QMessageBox.warning(
                self,
                "Missing Files",
                "Please select x.grd, y.grd, and bed.dep files as a template."
                )
            return

        if not output_dir or not os.path.isdir(output_dir):
            QtWidgets.QMessageBox.warning(
                self,
                "Invalid Path",
                "Please select a valid output directory."
            )
            return

        try:
            E, N, Z = load_grid_files(path_x, path_y, path_z)
        except FILE_IO_ERRORS as exc:
            QtWidgets.QMessageBox.critical(
                self, "Error Loading Files",
                f"Failed to load template grid/depth files: {exc}"
            )
            return

        if not (E.shape == N.shape == Z.shape):
            QtWidgets.QMessageBox.critical(
                self,
                "Shape Mismatch",
                "The selected files must have the same dimensions "
                "(rows x columns)."
            )
            return

        grid_crs = self.iface.mapCanvas().mapSettings().destinationCrs()

        self.iface.messageBar().pushMessage(
            "QBeach",
            "Generating optional files...",
            level=QGIS_INFO,
            duration=2
        )

        # Manning
        if self.cbManningLayer.isChecked():
            default_val = self.dsbDefaultManning.value()

            if self.cbManningDefaultOnly.isChecked():
                manning_grid = np.full_like(Z, default_val, dtype=float)
            else:
                layer = self.mlcbManningSource.currentLayer()
                attribute = self.cbManningHeading.currentText()

                if not layer or not attribute:
                    QtWidgets.QMessageBox.warning(
                        self,
                        "Manning Layer Error",
                        "Please select a Manning layer and attribute field."
                    )
                    return

                try:
                    manning_grid = sample_vector_at_grid(
                        layer,
                        attribute,
                        default_val,
                        E,
                        N,
                        destination_crs=grid_crs
                    )
                except LAYER_SAMPLE_ERRORS as exc:
                    QtWidgets.QMessageBox.critical(
                        self,
                        "Manning Error",
                        f"Failed to generate manning.dep: {exc}"
                    )
                    return

            try:
                np.savetxt(
                    os.path.join(output_dir, "manning.dep"),
                    manning_grid,
                    fmt="%.4f"
                )
            except FILE_IO_ERRORS as exc:
                QtWidgets.QMessageBox.critical(
                    self,
                    "Manning Error",
                    f"Failed to save manning.dep: {exc}"
                )
                return

        # Non-Erodible
        if self.cbNonErodibleLayer.isChecked():
            default_val = self.dsbDefaultNE.value()

            if self.cbNeDefaultOnly.isChecked():
                ne_grid = np.full_like(Z, default_val, dtype=float)
            else:
                layer = self.mlcbNonErodibleSource.currentLayer()
                attribute = self.cbNonErodibleHeading.currentText()

                if not layer or not attribute:
                    QtWidgets.QMessageBox.warning(
                        self,
                        "Non-Erodible Error",
                        "Please select a NE layer and attribute field."
                    )
                    return

                try:
                    ne_grid = sample_vector_at_grid(
                        layer,
                        attribute,
                        default_val,
                        E,
                        N,
                        destination_crs=grid_crs
                    )
                except LAYER_SAMPLE_ERRORS as exc:
                    QtWidgets.QMessageBox.critical(
                        self,
                        "Non-Erodible Error",
                        f"Failed to generate nonerodible.dep: {exc}"
                    )
                    return

            try:
                np.savetxt(
                    os.path.join(output_dir, "nonerodible.dep"),
                    ne_grid,
                    fmt="%.4f")
            except FILE_IO_ERRORS as exc:
                QtWidgets.QMessageBox.critical(
                    self,
                    "Non-Erodible Error",
                    f"Failed to save nonerodible.dep: {exc}"
                )
                return

            # (Future: handle Sediment)

        QTimer.singleShot(2500, lambda: QtWidgets.QMessageBox.information(
                self, "Success", f"Optional files saved to {output_dir}"))

