    def getModelParams(self):

        nx = 0
        ny = 0
        alfa = 0.0
        path_x = self.xgrdQgsFileWidget2.filePath()
        path_y = self.ygrdQgsFileWidget2.filePath()
        path_z = self.beddepQgsFileWidget2.filePath()

        found_grid = False
        if os.path.isfile(path_x) and os.path.isfile(path_y):
            try:
                X = np.loadtxt(path_x)
                Y = np.loadtxt(path_y)

                # standard 2D grid case
                if X.ndim == 2 and Y.ndim == 2 and X.shape == Y.shape:
                    rows, cols = X.shape
                    nx = cols - 1
                    ny = rows - 1
                    found_grid = True

                # 1D profile case (ny = 0)
                elif X.ndim == 1 and Y.ndim == 1 and X.shape == Y.shape:
                    nx = len(X) - 1
                    ny = 0
                    found_grid = True

            except FILE_IO_ERRORS as exc:
                logger.debug("Could not load coordinate grid files: %s", exc)

        if not found_grid:
            for path in [path_x, path_y, path_z]:
                if path and os.path.isfile(path):
                    try:
                        data = np.loadtxt(path)
                        if data.ndim == 2:
                            rows, cols = data.shape
                            nx = cols - 1
                            ny = rows - 1
                            break
                        elif data.ndim == 1:
                            nx = len(data) - 1
                            ny = 0
                            break
                    except FILE_IO_ERRORS as exc:
                        logger.warning(
                            "Could not load fallback grid data from %s: %s",
                            path,
                            exc
                        )

        # limit angles to [0, 360]
        main_angle = self.dsbWaveDirection.value()
        thetamin = (main_angle - 90) % 360
        thetamax = (main_angle + 90) % 360

        # get global variables (checkboxes + line edit)
        var_map = {
            self.cbCelerity: "c",
            self.cbEnergy: "E",
            self.cbWaveHeight: "H",
            self.cbSedero: "sedero",
            self.cbMeanWaveAngle: "thetamean",
            self.cbBedLevel: "zb",
            self.cbWaterLevel: "zs"
        }

        selected_vars = [
            name for cb,
            name in var_map.items() if cb.isChecked()
        ]

        other_vars = self.leOutputVariables.text()
        if other_vars:
            extra_vars = [
                v.strip() for v in other_vars.split(',') if v.strip()
            ]
            selected_vars.extend(extra_vars)

        selected_vars = sorted(set(selected_vars))

        # get mean variables (checkboxes + line edit)
        mean_var_map = {
            self.cbCelerityMean: "c",
            self.cbEnergyMean: "E",
            self.cbWaveHeightMean: "H",
            self.cbSederoMean: "sedero",
            self.cbMeanU: "u",
            self.cbMeanV: "v",
            self.cbWaterLevelMean: "zs"
        }

        selected_means = [
            name for cb, name in mean_var_map.items() if cb.isChecked()
        ]

        other_means = self.leOtherMeans.text()
        if other_means:
            extra_means = [
                v.strip() for v in other_means.split(',') if v.strip()
            ]
            selected_means.extend(extra_means)

        selected_means = sorted(set(selected_means))

        # optional bed friction from manning .dep file
        bedfriction = ""
        if self.cbUseManning.isChecked():
            manning_path = self.qfwOptionalManning.filePath()
            if manning_path and manning_path.lower().endswith('.dep'):
                bedfriction = (
                    f"{'bedfriction':<13}= manning\n"
                    f"{'bedfricfile':<13}= {os.path.basename(manning_path)}"
                )

        # optional non-erodible .dep file handling
        sedimentation = f"{'morphology':<13}= 0\n{'sedtrans':<13}= 0"
        if self.cbUseNonErodible.isChecked():
            ne_path = self.qfwOptionalNonErodible.filePath()
            if ne_path and ne_path.lower().endswith('.dep'):
                sedimentation = (
                    f"{'morfac':<13}= 1\n"
                    f"{'struct':<13}= 1\n"
                    f"{'ne_layer':<13}= {os.path.basename(ne_path)}"
                )

        # optional wind: constant spinboxes, or wind.txt from a table
        wind = f"{'wind':<13}= 0"
        if self.cbVariableWind.isChecked():
            wind = (
                f"{'wind':<13}= 1\n"
                f"{'windfile':<13}= wind.txt"
            )
        elif self.dsbWindSpeed.value() > 0:
            wind = (
                f"{'wind':<13}= 1\n"
                f"{'windv':<13}= {self.dsbWindSpeed.value()}\n"
                f"{'windth':<13}= {self.dsbWindDirection.value()}"
            )

        return {
            'date': datetime.datetime.now().strftime("%Y-%m-%d"),
            'duration': self.sbModelDuration.value(),
            'tstop': self.sbModelDuration.value()+1,
            'tintg': self.sbTimestep.value(),
            'tide': self.dsbTide.value(),
            'Hm0': self.dsbWaveHeight.value(),
            'Tp': self.dsbWavePeriod.value(),
            'mainAngle': main_angle,
            'thetamin': thetamin,
            'thetamax': thetamax,
            'spread': self.dsbSpreading.value(),
            'gammajsp': self.dsbGammaJSP.value(),
            'windspeed': self.dsbWindSpeed.value(),
            'winddir': self.dsbWindDirection.value(),
            'wind': wind,
            'alfa': alfa,
            'nx': nx,
            'ny': ny,
            'nglobalvar': len(selected_vars),
            'global_vars': "\n".join(selected_vars),
            'nmeanvar': len(selected_means),
            'mean_vars': "\n".join(selected_means),
            'bedfriction': bedfriction,
            'sedimentation': sedimentation
        }

    def exportModel(self):

        output_dir = self.fwSetwd2.filePath()
        plugin_dir = os.path.dirname(__file__)
        params_template = os.path.join(plugin_dir, 'ParamsTemplate.txt')
        p2 = self.getModelParams()

        if (p2['nglobalvar'] + p2['nmeanvar']) == 0:
            QtWidgets.QMessageBox.warning(
                self,
                "No Output Variables",
                "Please select at least one output variable "
                "(Global or Mean) before exporting."
            )
            return

        if not all([
            self.xgrdQgsFileWidget2.filePath(),
            self.ygrdQgsFileWidget2.filePath(),
            self.beddepQgsFileWidget2.filePath()
        ]):
            QtWidgets.QMessageBox.warning(
                self,
                "Missing Files",
                "Please select x.grd, y.grd, and bed.dep files."
            )
            return

        if not output_dir or not os.path.isdir(output_dir):
            QtWidgets.QMessageBox.warning(
                self,
                "Invalid Directory",
                "Please select a valid output directory."
            )
            return

        missing_optional = []
        if self.cbUseManning.isChecked():
            manning_sel = self.qfwOptionalManning.filePath()
            if not manning_sel or not manning_sel.lower().endswith('.dep'):
                missing_optional.append("Manning")
        if self.cbUseNonErodible.isChecked():
            ne_sel = self.qfwOptionalNonErodible.filePath()
            if not ne_sel or not ne_sel.lower().endswith('.dep'):
                missing_optional.append("Non-erodible")
        if missing_optional:
            QtWidgets.QMessageBox.warning(
                self,
                "Missing Optional Files",
                "The following optional .dep files "
                "are enabled but not selected:\n"
                + "\n".join(f"- {name}" for name in missing_optional)
            )
            return

        # time-varying tides: validate selections
        if self.cbVariableTides.isChecked():
            tide_layer = self.mlcbTideTable.currentLayer()
            date_field = self.cbDateColumn.currentText()
            time_field = self.cbTimeColumn.currentText()
            left_field = self.cbLeftTideColumn.currentText()
            right_field = self.cbRightTideColumn.currentText()

            missing_tide = []
            if not (tide_layer and tide_layer.isValid()):
                missing_tide.append("Tide table layer")
            if not date_field:
                missing_tide.append("Date column")
            if not time_field:
                missing_tide.append("Time column")
            if not left_field:
                missing_tide.append("Left tide column")
            if missing_tide:
                QtWidgets.QMessageBox.warning(
                    self, "Missing Tide Table Settings",
                    "The following time-varying tide settings "
                    "are incomplete:\n"
                    + "\n".join(f"- {name}" for name in missing_tide))
                return

        # time-varying wind: validate selections
        if self.cbVariableWind.isChecked():
            wind_layer = self.mlcbWindTable.currentLayer()
            wind_date_field = self.cbWindDate.currentText()
            wind_time_field = self.cbWindTime.currentText()
            speed_field = self.cbSpeedColumn.currentText()
            wind_dir_field = self.cbWindDirColumn.currentText()

            missing_wind = []
            if not (wind_layer and wind_layer.isValid()):
                missing_wind.append("Wind table layer")
            if not wind_date_field:
                missing_wind.append("Date column")
            if not wind_time_field:
                missing_wind.append("Time column")
            if not speed_field:
                missing_wind.append("Wind speed column")
            if not wind_dir_field:
                missing_wind.append("Wind direction column")
            if missing_wind:
                QtWidgets.QMessageBox.warning(
                    self, "Missing Wind Table Settings",
                    "The following time-varying wind settings "
                    "are incomplete:\n"
                    + "\n".join(f"- {name}" for name in missing_wind))
                return

        # time-varying waves: validate selections
        if self.cbVariableWaves.isChecked():
            wave_layer = self.mlcbWaveTable.currentLayer()
            wave_date_field = self.cbWaveDate.currentText()
            wave_time_field = self.cbWaveTime.currentText()
            height_field = self.cbHeightColumn.currentText()
            period_field = self.cbPeriodColumn.currentText()
            direction_field = self.cbDirectionColumn.currentText()

            missing_wave = []
            if not (wave_layer and wave_layer.isValid()):
                missing_wave.append("Wave table layer")
            if not wave_date_field:
                missing_wave.append("Date column")
            if not wave_time_field:
                missing_wave.append("Time column")
            if not height_field:
                missing_wave.append("Wave height column")
            if not period_field:
                missing_wave.append("Wave period column")
            if not direction_field:
                missing_wave.append("Wave direction column")
            if missing_wave:
                QtWidgets.QMessageBox.warning(
                    self, "Missing Wave Table Settings",
                    "The following time-varying wave settings "
                    "are incomplete:\n"
                    + "\n".join(f"- {name}" for name in missing_wave)
                )
                return

        # one overlap check shared by every active table
        blocked, overlap_window = self._export_overlap_window()
        if blocked:
            return

        # build tide rows
        tide_rows = None
        if self.cbVariableTides.isChecked():
            tide_rows = layer_tide_rows(
                tide_layer, date_field, time_field, left_field,
                right_field or None, window=overlap_window)
            if not tide_rows:
                QtWidgets.QMessageBox.warning(
                    self, "Invalid Tide Table",
                    "The selected tide table must contain at least two "
                    "valid rows with usable date, time, and tide values."
                )
                return

        # build wind rows
        wind_rows = None
        if self.cbVariableWind.isChecked():
            wind_rows = layer_wind_rows(
                wind_layer, wind_date_field, wind_time_field, speed_field,
                wind_dir_field, window=overlap_window)
            if not wind_rows:
                QtWidgets.QMessageBox.warning(
                    self, "Invalid Wind Table",
                    "The selected wind table must contain at least two "
                    "valid rows with usable date, time, wind speed, and "
                    "wind direction values."
                )
                return

        # build sea-state rows
        wave_rows = None
        if self.cbVariableWaves.isChecked():
            wave_rows = layer_wave_rows(
                wave_layer, wave_date_field, wave_time_field, height_field,
                period_field, direction_field, window=overlap_window)
            if not wave_rows:
                QtWidgets.QMessageBox.warning(
                    self, "Invalid Wave Table",
                    "The selected wave table must contain at least two "
                    "valid rows with usable date, time, height, period, "
                    "and direction values."
                )
                return

        align_info = None
        if tide_rows or wave_rows or wind_rows:
            tide_rows, wave_rows, wind_rows, align_info = align_series(
                tide_rows, wave_rows, p2['duration'], wind_rows=wind_rows)
            if align_info:
                steps = ", ".join(
                    f"{label} step {align_info[key]} s"
                    for label, key in (("Tide", "tide_step"),
                                       ("Wave", "wave_step"),
                                       ("Wind", "wind_step"))
                    if key in align_info)
                self.iface.messageBar().pushMessage(
                    "Aligned timesteps:",
                    f"{steps} \u2192 shared {align_info['base']} s grid.",
                    level=QGIS_SUCCESS,
                    duration=4)

        min_wave_segment = None
        if wave_rows:
            min_wave_segment = (align_info['base'] if align_info
                                else series_step(wave_rows, min_step=1))

        try:
            export_xbeach_model(output_dir, params_template, p2,
                                tide_rows=tide_rows, wave_rows=wave_rows,
                                min_wave_segment=min_wave_segment,
                                wind_rows=wind_rows)

            self.iface.messageBar().pushMessage(
                "Working on it:",
                "Preparing model files.",
                level=QGIS_SUCCESS,
                duration=2
            )
            QTimer.singleShot(2500, lambda: QtWidgets.QMessageBox.information(
                self, "Success", f"Model files exported to {output_dir}"))
        except PARAMS_EXPORT_ERRORS as exc:
            QtWidgets.QMessageBox.critical(
                self,
                "Error",
                f"Failed to export model: {exc}"
            )

